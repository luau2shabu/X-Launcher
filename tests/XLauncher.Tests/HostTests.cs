public sealed class AppTests
{
    [Theory]
    [InlineData("Netflix", "4DF9E0F8.Netflix_mcm4njqhnhss8!Netflix.App", true)]
    [InlineData("Plex HTPC", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Plex\Plex HTPC\Plex HTPC.exe", true)]
    [InlineData("YouTube", "Chrome._crx_agimnkijcamfeangaknmldooml", true)]
    [InlineData("Uninstall Kodi", @"{6D809377-6AF0-444B-8957-A3773F02200E}\Kodi\Uninstall.exe", false)]
    [InlineData("Visit Kodi Online", "http://kodi.tv", false)]
    [InlineData("VLC media player - reset preferences and cache files", "Microsoft.AutoGenerated.{51325390}", false)]
    [InlineData("Read me", @"C:\Program Files\App\readme.txt", false)]
    [InlineData("Manual", @"C:\Program Files\App\guide.pdf", false)]
    public void Filter_keeps_apps_and_drops_noise(string name, string path, bool expected) =>
        Assert.Equal(expected, AppFilter.IsLaunchable(name, path));

    [Fact]
    public void Kind_distinguishes_store_apps()
    {
        Assert.Equal("store", AppFilter.KindOf("Microsoft.WindowsCalculator_8wekyb3d8bbwe!App"));
        Assert.Equal("desktop", AppFilter.KindOf(@"{6D809377-6AF0-444B-8957-A3773F02200E}\VideoLAN\VLC\vlc.exe"));
        Assert.Equal("desktop", AppFilter.KindOf("MSEdge"));
    }

    static readonly AppEntry[] Installed =
    [
        new("Chrome._crx_yt", "YouTube", "desktop", null, false),
        new("4DF9E0F8.Netflix_mcm4njqhnhss8!Netflix.App", "Netflix", "store", null, false),
        new(@"{6D809377}\Plex\Plex HTPC\Plex HTPC.exe", "Plex HTPC", "desktop", null, false),
        new(@"{6D809377}\Plex\Plex\Plex.exe", "Plex", "desktop", null, false),
        new("SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify", "Spotify", "store", null, false),
    ];

    [Fact]
    public void Seeder_adds_websites_for_missing_services_and_tv_youtube()
    {
        var websites = AppSeeder.MissingWebsites(Installed);

        Assert.Equal(["YouTube", "Prime Video", "HBO Max"], websites.Select(w => w.Name));
        Assert.True(websites[0].TvMode);
        Assert.All(websites, w => Assert.Equal("url", w.Kind));
    }

    [Fact]
    public void Seeder_orders_favorites_and_prefers_tv_mode_youtube()
    {
        var tvYouTube = new AppEntry("custom:yt", "YouTube", "url", null, true, "https://www.youtube.com/tv", TvMode: true);

        var favorites = AppSeeder.PickFavorites([tvYouTube, .. Installed]);

        Assert.Equal(
            [@"{6D809377}\Plex\Plex HTPC\Plex HTPC.exe", "4DF9E0F8.Netflix_mcm4njqhnhss8!Netflix.App", "custom:yt", "SpotifyAB.SpotifyMusic_zpdnekdrzrea0!Spotify"],
            favorites);
    }
}

public sealed class PlexTests
{
    const string Episode = """
    {
      "ratingKey": "501", "type": "episode", "title": "Pilot", "grandparentTitle": "Severance",
      "grandparentRatingKey": "500", "parentRatingKey": "499", "parentIndex": 1, "index": 1,
      "thumb": "/library/metadata/501/thumb/1", "grandparentThumb": "/library/metadata/500/thumb/1",
      "grandparentArt": "/library/metadata/500/art/1", "duration": 3000000, "viewOffset": 750000,
      "librarySectionID": "2", "lastViewedAt": 1790000000,
      "Media": [{ "videoResolution": "4k", "Part": [{ "Stream": [
        { "streamType": 1, "DOVIPresent": true, "colorTrc": "smpte2084", "displayTitle": "4K DoVi/HDR10 (HEVC Main 10)" },
        { "streamType": 2, "codec": "truehd", "channels": 8, "displayTitle": "English (TrueHD 7.1 Atmos)", "selected": true }
      ]}]}]
    }
    """;

    [Fact]
    public void Episode_maps_to_show_title_progress_and_images()
    {
        using var doc = JsonDocument.Parse(Episode);

        var item = PlexMapper.ToItem(doc.RootElement, "srv", "Home");

        Assert.Equal("Severance", item.Title);
        Assert.Equal("S1 E1 · Pilot", item.Subtitle);
        Assert.Equal("500", item.ShowKey);
        Assert.Equal(0.25, item.Progress, 3);
        Assert.False(item.Watched);
        Assert.StartsWith("https://img.xlauncher.local/plex/srv/360x540?u=%2Flibrary%2Fmetadata%2F500%2Fthumb", item.Poster);
        Assert.Contains("/640x360?u=%2Flibrary%2Fmetadata%2F501%2Fthumb", item.Landscape);
        Assert.Contains("%2F500%2Fart", item.Art);
    }

    [Fact]
    public void Badges_read_dolby_vision_hdr_and_atmos()
    {
        using var doc = JsonDocument.Parse(Episode);

        Assert.Equal(["4K", "Dolby Vision", "HDR10", "Dolby Atmos", "7.1"], PlexBadges.From(doc.RootElement));
    }

    [Fact]
    public void Badges_handle_dts_hd_from_list_summary()
    {
        using var doc = JsonDocument.Parse("""{ "Media": [{ "videoResolution": "1080", "audioCodec": "dca", "audioProfile": "ma", "audioChannels": "6" }] }""");

        Assert.Equal(["HD", "DTS-HD MA", "5.1"], PlexBadges.From(doc.RootElement));
    }

    [Fact]
    public void Show_is_watched_when_all_episodes_are()
    {
        using var doc = JsonDocument.Parse("""{ "ratingKey": "9", "type": "show", "title": "X", "year": 2020, "leafCount": 10, "viewedLeafCount": 10 }""");

        var item = PlexMapper.ToItem(doc.RootElement, "s", "n");

        Assert.True(item.Watched);
        Assert.Equal("2020", item.Subtitle);
    }

    [Fact]
    public void Show_details_carry_the_next_episode()
    {
        using var doc = JsonDocument.Parse($$"""{ "ratingKey": "500", "type": "show", "title": "Severance", "OnDeck": { "Metadata": [{{Episode}}] } }""");

        var item = PlexMapper.ToItem(doc.RootElement, "s", "n");

        Assert.Equal("501", item.OnDeck?.Key);
    }

    [Fact]
    public void Htpc_client_id_is_read_from_web_section()
    {
        const string ini = "[General]\nClientID=wrong\n\n[web]\nVERSION=12\nClientID=9i9mwctchldf73mvy2a7cy65\r\nPlexAuthToken=secret\n";

        Assert.Equal("9i9mwctchldf73mvy2a7cy65", HtpcConfig.ParseClientId(ini));
        Assert.Null(HtpcConfig.ParseClientId("[web]\nVERSION=12\n"));
    }

    [Fact]
    public void Dedup_matches_translated_copies_by_agent_guid()
    {
        var english = new PlexItem { Server = "a", Key = "1", Type = "movie", Title = "Wake Up Dead Man", Year = 2025, Guid = "plex://movie/abc" };
        var thai = new PlexItem { Server = "b", Key = "9", Type = "movie", Title = "ฆาตกรรมหรรษา", Year = 2025, Guid = "plex://movie/abc" };
        var local = new PlexItem { Server = "a", Key = "2", Type = "movie", Title = "Home Video", Year = 2020, Guid = "local://2" };
        var copy = new PlexItem { Server = "a", Key = "3", Type = "movie", Title = "home video ", Year = 2020, Guid = "local://3" };

        Assert.Equal(PlexService.DedupKey(english), PlexService.DedupKey(thai));
        Assert.Equal(PlexService.DedupKey(local), PlexService.DedupKey(copy));
        Assert.NotEqual(PlexService.DedupKey(english), PlexService.DedupKey(local));
    }

    [Fact]
    public void Interleave_round_robins_lists()
    {
        IReadOnlyList<int>[] lists = [[1, 2, 3], [10], [20, 21]];

        Assert.Equal([1, 10, 20, 2, 21, 3], PlexService.Interleave(lists));
    }

    [Fact]
    public void Daily_shuffle_is_stable_within_a_day_and_changes_between_days()
    {
        var items = Enumerable.Range(0, 50).ToList();
        var day = new DateOnly(2026, 10, 29);

        var first = DailyShuffle.Apply(items, "srv/1", day);
        var again = DailyShuffle.Apply(items, "srv/1", day);
        var tomorrow = DailyShuffle.Apply(items, "srv/1", day.AddDays(1));

        Assert.Equal(first, again);
        Assert.NotEqual(first, tomorrow);
        Assert.Equal(items, first.Order());
    }
}
