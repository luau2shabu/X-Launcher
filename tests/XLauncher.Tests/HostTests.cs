public sealed class BridgeHostTests
{
    [Fact]
    public async Task Dispatch_returns_result_with_request_id()
    {
        var bridge = new BridgeHost();
        bridge.On("math.add", p => p.Num("a", 0) + p.Num("b", 0));

        var response = await bridge.DispatchAsync("""{ "id": 7, "method": "math.add", "params": { "a": 2, "b": 3 } }""");

        using var doc = JsonDocument.Parse(response!);
        Assert.Equal(7, doc.RootElement.GetProperty("id").GetInt32());
        Assert.Equal(5, doc.RootElement.GetProperty("result").GetInt32());
    }

    [Fact]
    public async Task Unknown_method_and_handler_errors_come_back_as_error()
    {
        var bridge = new BridgeHost();
        bridge.On("boom", (Func<JsonElement, object?>)(_ => throw new InvalidOperationException("nope")));

        var unknown = JsonDocument.Parse((await bridge.DispatchAsync("""{ "id": 1, "method": "missing" }"""))!);
        var failed = JsonDocument.Parse((await bridge.DispatchAsync("""{ "id": 2, "method": "boom" }"""))!);

        Assert.Contains("Unknown method", unknown.RootElement.GetProperty("error").GetString());
        Assert.Equal("nope", failed.RootElement.GetProperty("error").GetString());
    }

    [Fact]
    public async Task Missing_required_param_is_an_error()
    {
        var bridge = new BridgeHost();
        bridge.On("echo", p => p.Req("text"));

        var response = JsonDocument.Parse((await bridge.DispatchAsync("""{ "id": 3, "method": "echo", "params": {} }"""))!);

        Assert.Contains("text", response.RootElement.GetProperty("error").GetString());
    }

    [Fact]
    public void Emit_produces_event_json()
    {
        var bridge = new BridgeHost();
        string? sent = null;
        bridge.Outgoing += json => sent = json;

        bridge.Emit("key", "ArrowUp");

        using var doc = JsonDocument.Parse(sent!);
        Assert.Equal("key", doc.RootElement.GetProperty("event").GetString());
        Assert.Equal("ArrowUp", doc.RootElement.GetProperty("data").GetString());
    }

    [Theory]
    [InlineData("netflix.com", "https://netflix.com/")]
    [InlineData(" https://www.youtube.com/tv ", "https://www.youtube.com/tv")]
    public void NormalizeUrl_adds_scheme(string input, string expected) =>
        Assert.Equal(expected, Routes.NormalizeUrl(input));

    [Theory]
    [InlineData("javascript:alert(1)")]
    [InlineData("file:///C:/Windows")]
    [InlineData("localhost")]
    public void NormalizeUrl_rejects_non_web_addresses(string input) =>
        Assert.Throws<ArgumentException>(() => Routes.NormalizeUrl(input));
}

